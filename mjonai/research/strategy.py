"""
Base Strategy interface for the MJONAI Research Engine.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from typing import Any

import pandas as pd

from mjonai.research.optimization.models import (
    ParameterDefinition,
    ParameterSet,
)


@dataclass(slots=True)
class StrategyResult:
    """
    One trading signal generated by a strategy.
    """

    symbol: str

    strategy_id: str

    signal: str

    score: float

    index: int

    metadata: dict[str, Any] = field(default_factory=dict)


class Strategy(ABC):
    """
    Base class for every research strategy.
    """

    @property
    @abstractmethod
    def name(self) -> str:
        ...

    @property
    @abstractmethod
    def version(self) -> str:
        ...

    @property
    @abstractmethod
    def timeframe(self) -> str:
        ...

    @property
    def description(self) -> str:
        return ""

    @property
    def markets(self) -> list[str]:
        return [
            "EQUITY",
        ]

    @property
    def direction(self) -> str:
        return "LONG"

    @property
    def tags(self) -> list[str]:
        return []

    @property
    def parameters(
        self,
    ) -> list[ParameterDefinition]:
        """
        Search space exposed for optimization.
        Default: no tunable parameters.
        """

        return []

    def configure(
        self,
        parameters: ParameterSet,
    ) -> None:
        """
        Apply one parameter set before execution.

        Strategies with tunable parameters should override
        this method.
        """

        return None

    @abstractmethod
    def generate_signal(
        self,
        data: pd.DataFrame,
    ) -> StrategyResult | None:
        """
        Return one signal or None.
        """
        ...